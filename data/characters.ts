/** Get character by ID */
export function getCharacterById(id: string): Character | undefined {
    return characters.find((c) => c.id === id);
}

/** Get characters by faction */
export function getCharactersByFaction(faction: Faction): Character[] {
    return characters.filter((c) => c.factions.includes(faction));
}

/** Get all unique factions */
export function getFactions(): Faction[] {
    return [...new Set(characters.flatMap((c) => c.factions))].sort() as Faction[];
}

/** Get all unique power types */
export function getPowerTypes(): PowerType[] {
    return [...new Set(characters.flatMap((c) => c.powerTypes))].sort() as PowerType[];
}

/** Search characters by name */
export function searchCharacters(query: string): Character[] {
    const q = query.toLowerCase();
    return characters.filter(
        (c) =>
            c.name.toLowerCase().includes(q) ||
            c.alias.toLowerCase().includes(q) ||
            c.realName.toLowerCase().includes(q)
    );
}
