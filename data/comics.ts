/** Get comic by ID */
export function getComicById(id: string): Comic | undefined {
    return comics.find((c) => c.id === id);
}

/** Get all unique eras */
export function getComicEras(): string[] {
    return [...new Set(comics.map((c) => c.era))];
}

/** Get all unique series */
export function getComicSeries(): string[] {
    return [...new Set(comics.map((c) => c.series))].sort();
}
