/** Get movie by ID */
export function getMovieById(id: string): Movie | undefined {
    return movies.find((m) => m.id === id);
}

/** Get movies by phase */
export function getMoviesByPhase(phase: number): Movie[] {
    return movies.filter((m) => m.phase === phase);
}

/** Get all unique phases */
export function getPhases(): number[] {
    return [...new Set(movies.map((m) => m.phase))].sort();
}

/** Get all unique genres */
export function getGenres(): string[] {
    return [...new Set(movies.flatMap((m) => m.genre))].sort();
}

/** Get all unique years */
export function getYears(): number[] {
    return [...new Set(movies.map((m) => m.year))].sort();
}
